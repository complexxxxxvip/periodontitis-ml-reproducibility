    imputation_variables = imputation_vars,
    derivation_rules = list(
      AG_ratio = "ALB/(TP-ALB)",
      INR = "(PT/13.1)^1.31",
      NPR = "NE_C/PLT",
      PAR = "PLT/ALB",
      TyG = "log(1594.26*TG*GLU/2)",
      eGFR = paste0(
        "141*min((CR/88.4)/kappa,1)^alpha*max((CR/88.4)/kappa,1)^(-1.209)",
        "*0.993^Age*sex_coefficient*race_coefficient"
      )
    ),
    egfr_settings = list(
      female_code = SEX_FEMALE_CODE,
      male_code = SEX_MALE_CODE,
      female_kappa = 0.7,
      male_kappa = 0.9,
      female_alpha = -0.329,
      male_alpha = -0.411,
      female_coefficient = 1.018,
