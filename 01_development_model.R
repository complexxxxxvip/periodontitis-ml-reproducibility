# 3.1 Convert outcome to a factor with severe periodontitis as the FIRST/event
#     level. This avoids event-level inconsistencies between different scripts.
to_stage_factor <- function(x) {
  x_chr <- trimws(tolower(as.character(x)))

  out <- dplyr::case_when(
    x_chr %in% c("stage1", "1") ~ "Stage1",
    x_chr %in% c("stage0", "0") ~ "Stage0",
    TRUE ~ NA_character_
  )

  if (anyNA(out)) {
    stop("PDstage contains missing or unrecognized values.")
  }

  factor(
    out,
    levels = c("Stage1", "Stage0")
  )
}

# 3.2 Deterministically derive the six non-imputed predictors from BASIC variables.
#
# Derived-predictor formulas:
#   AG_ratio = ALB / (TP - ALB)
#   INR      = (PT / 13.1)^1.31
#   NPR      = NE_C / PLT
#   PAR      = PLT / ALB
#   TyG      = ln(1594.26 * TG * GLU / 2)
#
# eGFR:
#   Scr_mg_dL = CR / 88.4
#   eGFR = 141 * min(Scr/kappa, 1)^alpha * max(Scr/kappa, 1)^(-1.209) *
#          0.993^Age * sex_coefficient * race_coefficient
#   female: kappa=0.7, alpha=-0.329, sex coefficient=1.018
#   male:   kappa=0.9, alpha=-0.411, sex coefficient=1
#
# strict = FALSE is used only for the raw pre-imputation audit, where missing
# source values are expected. strict = TRUE is used after MICE completion.
derive_model_predictors <- function(
    df,
    strict = TRUE,
    female_code = SEX_FEMALE_CODE,
    male_code = SEX_MALE_CODE,
    race_coefficient = EGFR_RACE_COEFFICIENT
) {
  required_basic <- imputation_vars
  missing_basic <- setdiff(required_basic, names(df))

  if (length(missing_basic) > 0) {
    stop(
      paste0(
        "Cannot derive model predictors. Missing BASIC columns: ",
        paste(missing_basic, collapse = ", ")
      )
    )
  }

  out <- as_tibble(df)

  out <- out |>
    mutate(
      across(
        all_of(required_basic),
        ~ suppressWarnings(as.numeric(.x))
      )
    )

  # Sex coding is required for the user-specified eGFR equation.
  sex_nonmissing <- out$Sex[!is.na(out$Sex)]
  if (length(sex_nonmissing) > 0 &&
      !all(sex_nonmissing %in% c(female_code, male_code))) {
    stop(
      paste0(
        "Sex contains values outside the configured codes ",
        female_code, " (female) and ", male_code, " (male)."
      )
    )
  }

  n <- nrow(out)

  scr_mg_dl <- out$CR / 88.4
  is_female <- out$Sex == female_code
  is_male <- out$Sex == male_code

  kappa <- ifelse(is_female, 0.7, ifelse(is_male, 0.9, NA_real_))
  alpha <- ifelse(is_female, -0.329, ifelse(is_male, -0.411, NA_real_))
  sex_coefficient <- ifelse(is_female, 1.018, ifelse(is_male, 1.0, NA_real_))

  # Initialize derived vectors so invalid raw/pre-imputation combinations become NA
  # without generating divide-by-zero / log warnings.
  AG_ratio_calc <- rep(NA_real_, n)
  eGFR_calc <- rep(NA_real_, n)
  PAR_calc <- rep(NA_real_, n)
  NPR_calc <- rep(NA_real_, n)
  INR_calc <- rep(NA_real_, n)
  TyG_calc <- rep(NA_real_, n)

  ag_denom <- out$TP - out$ALB
  idx_ag <- !is.na(out$ALB) & !is.na(ag_denom) & ag_denom > 0
  AG_ratio_calc[idx_ag] <- out$ALB[idx_ag] / ag_denom[idx_ag]

  idx_egfr <- (
    !is.na(scr_mg_dl) & scr_mg_dl > 0 &
      !is.na(out$Age) & out$Age >= 0 &
      !is.na(kappa) & !is.na(alpha) & !is.na(sex_coefficient)
  )
  if (any(idx_egfr)) {
    scr_ratio_valid <- scr_mg_dl[idx_egfr] / kappa[idx_egfr]
    eGFR_calc[idx_egfr] <-
      141 *
      pmin(scr_ratio_valid, 1)^alpha[idx_egfr] *
      pmax(scr_ratio_valid, 1)^(-1.209) *
      0.993^out$Age[idx_egfr] *
      sex_coefficient[idx_egfr] *
      race_coefficient
  }

  idx_par <- !is.na(out$PLT) & !is.na(out$ALB) & out$ALB > 0
  PAR_calc[idx_par] <- out$PLT[idx_par] / out$ALB[idx_par]

  idx_npr <- !is.na(out$NE_C) & !is.na(out$PLT) & out$PLT > 0
  NPR_calc[idx_npr] <- out$NE_C[idx_npr] / out$PLT[idx_npr]

  idx_inr <- !is.na(out$PT) & out$PT > 0
  INR_calc[idx_inr] <- (out$PT[idx_inr] / 13.1)^1.31

  tyg_arg <- 1594.26 * out$TG * out$GLU / 2
  idx_tyg <- !is.na(tyg_arg) & tyg_arg > 0
  TyG_calc[idx_tyg] <- log(tyg_arg[idx_tyg])

  derived <- tibble(
    Sex = out$Sex,
    Smoke = out$Smoke,
    Age = out$Age,
    AG_ratio = AG_ratio_calc,
    eGFR = eGFR_calc,
    Fbg = out$Fbg,
    PAR = PAR_calc,
    TC = out$TC,
    GGT = out$GGT,
    ALP = out$ALP,
    NPR = NPR_calc,
    INR = INR_calc,
    HB = out$HB,
    APTT = out$APTT,
    LDH = out$LDH,
    TyG = TyG_calc
  ) |>
    select(all_of(predictor_vars))

  if (strict && anyNA(derived)) {
    bad_cols <- names(derived)[vapply(derived, anyNA, logical(1))]
    stop(
      paste0(
        "Derived model predictors contain missing/invalid values after MICE: ",
        paste(bad_cols, collapse = ", "),
        ". Check source values (especially TP>ALB, CR>0, ALB>0, PLT>0, ",
        "PT>0, TG>0, GLU>0) and Sex coding."
      )
    )
  }

  if (strict) {
    nonfinite_cols <- names(derived)[
      vapply(
        derived,
        function(x) any(!is.finite(as.numeric(x))),
        logical(1)
      )
    ]

    if (length(nonfinite_cols) > 0) {
      stop(
        paste0(
          "Non-finite derived/model values found after MICE: ",
          paste(nonfinite_cols, collapse = ", ")
        )
      )
    }
  }

  derived
}

# 3.3 TRUE MICE-PMM multiple imputation.
#     IMPORTANT:
#     - ONLY the 18 BASIC/source variables are supplied to this function.
#     - The six derived predictors are absent from mice() and cannot be imputed.
#     - Outcome PDstage, patient ID, and stage source are never used for imputation.
#     - ALL m completed datasets are returned; none are discarded.
mice_impute_predictors <- function(
    predictor_df,
    ignore_vec = NULL,
    seed = SEED,
    m = MICE_M,
    maxit = MICE_MAXIT,
    method_name = MICE_METHOD,
    print_flag = MICE_PRINT_FLAG,
    eps = MICE_EPS
) {
  dat <- as.data.frame(predictor_df)

  if (m < 1 || m != as.integer(m)) {
    stop("m must be a positive integer.")
  }

  # All 18 BASIC/source variables are numeric in this analysis, including binary 0/1 variables.
  for (nm in names(dat)) {
    dat[[nm]] <- suppressWarnings(as.numeric(dat[[nm]]))
  }

  if (is.null(ignore_vec)) {
    ignore_vec <- rep(FALSE, nrow(dat))
  }

  if (length(ignore_vec) != nrow(dat)) {
    stop("ignore_vec length does not match number of rows.")
  }

  # If there are no missing values, still return m identical completed datasets.
  # This keeps downstream multiple-imputation logic structurally consistent.
  if (!anyNA(dat)) {
    completed_list <- lapply(
      seq_len(m),
      function(j) as_tibble(dat)
    )
    names(completed_list) <- paste0("Imp", seq_len(m))

    return(list(
      completed_list = completed_list,
      mids = NULL,
      method = setNames(rep("", ncol(dat)), names(dat)),
      predictorMatrix = NULL,
      loggedEvents = NULL,
      m = m
    ))
  }

  method_vec <- mice::make.method(dat)
  method_vec[] <- ""

  has_missing <- vapply(dat, anyNA, logical(1))
  method_vec[has_missing] <- method_name

  pred_mat <- mice::make.predictorMatrix(dat)
  diag(pred_mat) <- 0

  # No outcome is present in dat, so outcome leakage is impossible here.
  set.seed(seed)
  imp <- mice::mice(
    dat,
    method = method_vec,
    predictorMatrix = pred_mat,
    m = m,
    maxit = maxit,
    ignore = ignore_vec,
    seed = seed,
    printFlag = print_flag,
    eps = eps
  )

  # TRUE multiple imputation: extract every completed dataset, not only action = 1.
  completed_list <- lapply(
    seq_len(m),
    function(j) {
      out <- mice::complete(imp, action = j) |>
        as_tibble()

      if (anyNA(out)) {
        stop(sprintf("MICE completed dataset %d still contains missing values.", j))
      }
      out
    }
  )
  names(completed_list) <- paste0("Imp", seq_len(m))

  list(
    completed_list = completed_list,
    mids = imp,
    method = method_vec,
    predictorMatrix = pred_mat,
    loggedEvents = imp$loggedEvents,
    m = m
  )
}


# 3.4 Build a CV object with fold-wise TRUE multiple imputation.
#
#     For each original CV fold:
#       analysis rows    -> ignore = FALSE -> estimate MICE models
#       assessment rows  -> ignore = TRUE  -> imputed but do not estimate models
#
#     Each fold yields MICE_M completed datasets. Therefore a 5-fold CV with
#     MICE_M = 5 produces 25 modeling resamples:
#       Fold01_Imp01 ... Fold01_Imp05
#       ...
#       Fold05_Imp01 ... Fold05_Imp05
#
#     Bayesian tuning evaluates all fold-imputation resamples. After the best
#     hyperparameters are selected, each patient's MICE_M OOF probabilities are
#     averaged to obtain one pooled OOF probability per base learner.
build_foldwise_mice_rset <- function(
    raw_model_df,
    raw_imputation_df,
    predictor_names,
    imputation_names,
    v = CV_FOLDS,
    m = MICE_M,
    seed = SEED
) {
  if (nrow(raw_model_df) != nrow(raw_imputation_df)) {
    stop("raw_model_df and raw_imputation_df must have identical row counts.")
  }

  source_for_split <- raw_model_df |>
    mutate(.row_id = seq_len(n()))

  set.seed(seed)
  base_folds <- vfold_cv(source_for_split, v = v, strata = PDstage)

  custom_splits <- list()
  custom_ids <- character(0)
  imputation_logs <- list()
  imputation_map <- list()
  mice_call_logs <- list()

  split_counter <- 0L

  for (i in seq_len(nrow(base_folds))) {
    cat(sprintf(
      "MICE preprocessing for Fold %d/%d: generating %d imputations ...\n",
      i, nrow(base_folds), m
    ))

    sp <- base_folds$splits[[i]]
    analysis_idx <- sort(rsample::analysis(sp)$.row_id)
    assessment_idx <- sort(rsample::assessment(sp)$.row_id)

    ignore_vec <- rep(TRUE, nrow(raw_model_df))
    ignore_vec[analysis_idx] <- FALSE

    # One MICE call creates m completed BASIC-variable datasets/chains for this fold.
    # None of AG_ratio/eGFR/PAR/NPR/INR/TyG is present in this mice() call.
    imp_i <- mice_impute_predictors(
      predictor_df = raw_imputation_df |> select(all_of(imputation_names)),
      ignore_vec = ignore_vec,
      seed = seed + i,
      m = m,
      eps = MICE_EPS
    )

    # Save one MICE diagnostic record per outer fold.
    mice_call_logs[[i]] <- list(
      Fold = i,
      Analysis_N = length(analysis_idx),
      Assessment_N = length(assessment_idx),
      MICE_method = imp_i$method,
      MICE_predictorMatrix = imp_i$predictorMatrix,
      MICE_eps = MICE_EPS,
      MICE_loggedEvents = imp_i$loggedEvents
    )

    for (j in seq_len(m)) {
      completed_basic <- imp_i$completed_list[[j]]

      # IMPORTANT: derive all six non-imputed predictors only AFTER MICE.
      # Observed values of AG_ratio/eGFR/PAR/NPR/INR/TyG in the source file
      # are intentionally ignored; the model uses deterministic recalculation
      # from the completed BASIC variables in every imputation.
      completed_predictors <- derive_model_predictors(
        completed_basic,
        strict = TRUE
      ) |>
        select(all_of(predictor_names))

      fold_data <- bind_cols(
        raw_model_df |> select(PDstage),
        completed_predictors
      )

      if (anyNA(fold_data)) {
        stop(sprintf(
          "Missing values remain in fold %d, imputation %d.",
          i, j
        ))
      }

      split_counter <- split_counter + 1L
      split_id <- sprintf("Fold%02d_Imp%02d", i, j)

      custom_splits[[split_counter]] <- rsample::make_splits(
        x = list(analysis = analysis_idx, assessment = assessment_idx),
        data = fold_data
      )
      custom_ids[split_counter] <- split_id

      imputation_map[[split_counter]] <- tibble(
        id = split_id,
        Fold = i,
        Imputation = j,
        Analysis_N = length(analysis_idx),
        Assessment_N = length(assessment_idx)
      )

      imputation_logs[[split_counter]] <- list(
        id = split_id,
        fold = i,
        imputation = j,
        analysis_n = length(analysis_idx),
        assessment_n = length(assessment_idx),
        method = imp_i$method,
        loggedEvents = imp_i$loggedEvents,
        derived_predictors = derived_vars
      )
    }
  }

  custom_rset <- rsample::manual_rset(
    splits = custom_splits,
    ids = custom_ids
  )

  list(
    rset = custom_rset,
    original_folds = base_folds,
    imputation_logs = imputation_logs,
    imputation_map = bind_rows(imputation_map),
    mice_call_logs = mice_call_logs
  )
}


# 3.5 Pool MICE-specific OOF probabilities to one probability per patient.
#     For machine-learning models, Rubin's coefficient pooling is generally not
#     available. We therefore fit/predict separately in every completed dataset
#     and integrate imputation uncertainty by averaging predicted probabilities.
pool_mi_oof_predictions <- function(
    pred_tbl,
    prob_col = ".pred_Stage1",
    pooled_name,
    expected_m = MICE_M
) {
  if (!(prob_col %in% names(pred_tbl))) {
    stop(paste0("Probability column not found: ", prob_col))
  }

  out <- pred_tbl |>
    group_by(.row, PDstage) |>
    summarise(
      MI_N = n(),
      Pooled_Probability = mean(.data[[prob_col]], na.rm = TRUE),
      MI_SD = ifelse(n() > 1, sd(.data[[prob_col]], na.rm = TRUE), 0),
      .groups = "drop"
    ) |>
    arrange(.row)

  if (any(out$MI_N != expected_m)) {
    bad <- out |> filter(MI_N != expected_m)
    stop(
      paste0(
        "OOF MI pooling count is incorrect. Expected ", expected_m,
        " predictions per patient; found mismatches for ",
        nrow(bad), " rows."
      )
    )
  }

  names(out)[names(out) == "Pooled_Probability"] <- pooled_name
  names(out)[names(out) == "MI_SD"] <- paste0(pooled_name, "_MI_SD")
  names(out)[names(out) == "MI_N"] <- paste0(pooled_name, "_MI_N")

  out
}


# 3.6 Metrics for model-building OOF probabilities.
#     These are development-stage diagnostics, NOT external validation results.
calculate_metrics <- function(truth, prob, threshold) {
  truth_chr <- as.character(truth)
  truth_num <- ifelse(truth_chr == "Stage1", 1, 0)

  pred_chr <- ifelse(prob >= threshold, "Stage1", "Stage0")

  TP <- sum(pred_chr == "Stage1" & truth_chr == "Stage1")
  TN <- sum(pred_chr == "Stage0" & truth_chr == "Stage0")
  FP <- sum(pred_chr == "Stage1" & truth_chr == "Stage0")
  FN <- sum(pred_chr == "Stage0" & truth_chr == "Stage1")

  sens <- TP / (TP + FN)
  spec <- TN / (TN + FP)
  acc <- (TP + TN) / (TP + TN + FP + FN)
  ppv <- TP / (TP + FP)
  npv <- TN / (TN + FN)
  f1 <- 2 * ppv * sens / (ppv + sens)
  gmean <- sqrt(sens * spec)

  roc_obj <- pROC::roc(
    response = factor(truth_chr, levels = c("Stage0", "Stage1")),
    predictor = prob,
    levels = c("Stage0", "Stage1"),
    direction = "<",
    quiet = TRUE
  )

  auc_value <- as.numeric(pROC::auc(roc_obj))
  brier <- mean((prob - truth_num)^2)

  # 10-bin ECE
  bins <- cut(
    prob,
    breaks = seq(0, 1, length.out = 11),
    include.lowest = TRUE,
    right = TRUE
  )

  ece_df <- tibble(
    prob = prob,
    truth = truth_num,
    bin = bins
  ) |>
    group_by(bin) |>
    summarise(
      n = n(),
      mean_prob = mean(prob),
      mean_obs = mean(truth),
      .groups = "drop"
    )

  ece <- sum(
    (ece_df$n / length(prob)) * abs(ece_df$mean_prob - ece_df$mean_obs)
  )

  tibble(
    Metric = c(
      "AUC", "Sensitivity", "Specificity", "Accuracy",
      "F1", "NPV", "PPV", "G_mean", "Brier", "ECE"
    ),
    Value = c(
      auc_value, sens, spec, acc,
      f1, npv, ppv, gmean, brier, ece
    )
  )
}

# 3.7 Convert best-parameter tibble into a long table for Excel.
best_params_to_long <- function(best_tbl, model_name) {
  x <- best_tbl
  if (".config" %in% names(x)) {
    x <- x |> select(-.config)
  }

  tibble(
    Model = model_name,
    Parameter = names(x),
    Value = vapply(x, function(z) as.character(z[[1]]), character(1))
  )
}

