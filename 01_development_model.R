# ==============================================================================
# 18. Optional external prediction helper
# ==============================================================================
# This function is defined here for convenience but is NOT run during training.
#
# Locked external prediction logic:
# - no external outcome is required to generate predictions;
# - external rows are ignore=TRUE in MICE and cannot estimate imputation rules;
# - external files provide the same 18 BASIC/source variables used by MICE;
# - exactly bundle$mice_settings$m external completed BASIC datasets are generated
#   when missing source variables require imputation;
# - AG_ratio/eGFR/PAR/NPR/INR/TyG are derived AFTER each external imputation;
# - each completed derived external dataset is paired with the corresponding
#   imputation-specific final SVM/XGBoost fit;
# - SVM and XGBoost probabilities are averaged across imputations FIRST;
# - the pooled base probabilities then enter the frozen meta-learner,
#   Platt calibrator, and frozen threshold.
#
# This matches the development-stage pooling rule used for the base OOF
# probabilities and avoids silently falling back to only the first imputation.
#
# Usage later:
#   bundle <- readRDS(
#     "private/model_objects/final_stacking_model_bundle.rds"
#   )
#   ext_raw <- read_excel("private/data/external_validation_data.xlsx", na = c("", "NA", "N/A"))
#   ext_pred <- predict_external_locked(ext_raw, bundle)
#
predict_external_locked <- function(external_raw, bundle, seed = SEED + 200) {

  required_predictors <- bundle$predictors
  imputation_names <- names(bundle$raw_development_imputation_data)
  m <- bundle$mice_settings$m

  if (is.null(bundle$final_svm_fits) || is.null(bundle$final_xgb_fits)) {
    stop(
      "Bundle does not contain TRUE-MI model lists (final_svm_fits/final_xgb_fits)."
    )
  }

  if (length(bundle$final_svm_fits) != m ||
      length(bundle$final_xgb_fits) != m) {
    stop("Number of fitted base models does not match bundle$mice_settings$m.")
  }

  ext <- as_tibble(external_raw)

  # External deployment requires the SAME 18 BASIC/source variables.
  # Derived predictors are intentionally NOT required from the external file.
  missing_required_basic <- setdiff(imputation_names, names(ext))
  if (length(missing_required_basic) > 0) {
    stop(
      paste0(
        "External data are missing required BASIC/source columns: ",
        paste(missing_required_basic, collapse = ", ")
      )
    )
  }

  ext_imp_input <- ext |>
    select(all_of(imputation_names)) |>
    mutate(
      across(
        everything(),
        ~ suppressWarnings(as.numeric(.x))
      )
    )

  # Validate binary coding in external data where observed.
  for (nm in c("Sex", "Smoke")) {
    vals <- sort(unique(ext_imp_input[[nm]][!is.na(ext_imp_input[[nm]])]))
    if (!all(vals %in% c(0, 1))) {
      stop(paste0("External ", nm, " must be coded as 0/1."))
    }
  }

  needs_imputation <- anyNA(ext_imp_input)

  # Create a list of m completed external BASIC-variable datasets.
  if (!needs_imputation) {

    ext_basic_complete_list <- lapply(
      seq_len(m),
      function(j) ext_imp_input
    )

  } else {

    dev_imp_raw <- bundle$raw_development_imputation_data

    combined <- bind_rows(
      dev_imp_raw,
      ext_imp_input
    )

    # Development rows estimate MICE relations; external rows do not.
    ignore_vec <- c(
      rep(FALSE, nrow(dev_imp_raw)),
      rep(TRUE, nrow(ext_imp_input))
    )

    imp_ext <- mice_impute_predictors(
      predictor_df = combined,
      ignore_vec = ignore_vec,
      seed = seed,
      m = m,
      maxit = bundle$mice_settings$maxit,
      method_name = bundle$mice_settings$method,
      print_flag = FALSE,
      eps = if (!is.null(bundle$mice_settings$eps)) {
        bundle$mice_settings$eps
      } else {
        MICE_EPS
      }
    )

    ext_basic_complete_list <- vector("list", m)

    for (j in seq_len(m)) {
      complete_j <- imp_ext$completed_list[[j]]

      ext_basic_complete_list[[j]] <- as_tibble(
        complete_j[
          (nrow(dev_imp_raw) + 1):nrow(complete_j),
          ,
          drop = FALSE
        ]
      )
    }
  }

  # Derive the six deterministic predictors separately within every completed
  # external BASIC-variable dataset, using the eGFR coding frozen in the bundle.
  frozen_female_code <- if (!is.null(bundle$egfr_settings$female_code)) {
    bundle$egfr_settings$female_code
  } else {
    SEX_FEMALE_CODE
  }
  frozen_male_code <- if (!is.null(bundle$egfr_settings$male_code)) {
    bundle$egfr_settings$male_code
  } else {
    SEX_MALE_CODE
  }
  frozen_race_coefficient <- if (!is.null(bundle$egfr_settings$race_coefficient)) {
    bundle$egfr_settings$race_coefficient
  } else {
    EGFR_RACE_COEFFICIENT
  }

  ext_complete_list <- lapply(
    ext_basic_complete_list,
    function(x) {
      derive_model_predictors(
        x,
        strict = TRUE,
        female_code = frozen_female_code,
        male_code = frozen_male_code,
        race_coefficient = frozen_race_coefficient
      ) |>
        select(all_of(required_predictors))
    }
  )

  if (any(vapply(ext_complete_list, anyNA, logical(1)))) {
    stop("Missing model predictors remain in at least one external MI dataset.")
  }

  # Predict separately with every imputation-specific fitted model.
  svm_prob_list <- vector("list", m)
  xgb_prob_list <- vector("list", m)

  for (j in seq_len(m)) {
    svm_prob_list[[j]] <- predict(
      bundle$final_svm_fits[[j]],
      new_data = ext_complete_list[[j]],
      type = "prob"
    )$.pred_Stage1

    xgb_prob_list[[j]] <- predict(
      bundle$final_xgb_fits[[j]],
      new_data = ext_complete_list[[j]],
      type = "prob"
    )$.pred_Stage1
  }

  svm_prob_mat <- do.call(cbind, svm_prob_list)
  xgb_prob_mat <- do.call(cbind, xgb_prob_list)

  # Locked prediction pooling rule: mean probability across imputations.
  svm_prob <- rowMeans(svm_prob_mat)
  xgb_prob <- rowMeans(xgb_prob_mat)

  svm_mi_sd <- if (m > 1) apply(svm_prob_mat, 1, sd) else rep(0, nrow(ext))
  xgb_mi_sd <- if (m > 1) apply(xgb_prob_mat, 1, sd) else rep(0, nrow(ext))

  meta_new <- tibble(
    SVM_z = (svm_prob - bundle$meta_scaler$SVM_mean) /
      bundle$meta_scaler$SVM_sd,
    XGB_z = (xgb_prob - bundle$meta_scaler$XGB_mean) /
      bundle$meta_scaler$XGB_sd
  )

  stack_raw <- predict(
    bundle$meta_fit,
    new_data = meta_new,
    type = "prob"
  )$.pred_Stage1

  stack_calibrated <- predict(
    bundle$platt_calibrator,
    newdata = data.frame(probs = stack_raw),
    type = "response"
  )

  tibble(
    SVM_probability = svm_prob,
    SVM_MI_SD = svm_mi_sd,
    XGBoost_probability = xgb_prob,
    XGBoost_MI_SD = xgb_mi_sd,
    Stacking_raw_probability = stack_raw,
    Predicted_probability = stack_calibrated,
    Predicted_class = ifelse(
      stack_calibrated >= bundle$final_threshold,
      "Stage1",
      "Stage0"
    )
  )
}
