  cat("\n==================== 9. REFIT FINAL BASE MODELS ACROSS IMPUTATIONS ====================\n")

  final_svm_fits <- vector("list", MICE_M)
  final_xgb_fits <- vector("list", MICE_M)

  for (j in seq_len(MICE_M)) {
    cat(sprintf("Final refit: imputation %d/%d ...\n", j, MICE_M))

    set.seed(SEED + 1000 + j)
    final_svm_fits[[j]] <- fit(
      svm_final_wf,
