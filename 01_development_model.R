# ==============================================================================
# Development Cohort: SVM + XGBoost Stacking Model
# TRUE multiple imputation of BASIC laboratory variables + deterministic derivation
# Full development cohort (n = 1321)
#
# Purpose
# 1) Read the non-imputed, non-standardized development dataset.
# 2) Use the prespecified 16 FINAL model predictors and fixed SVM + XGBoost stacking architecture.
# 3) MICE imputes ONLY the 18 basic/source variables:
#       Sex, Smoke, Age, TP, ALB, CR, Fbg, PLT, TC, GGT, ALP,
#       NE_C, PT, HB, APTT, LDH, GLU, TG.
# 4) The six derived predictors are NEVER independently imputed:
#       AG_ratio = ALB / (TP - ALB)
#       eGFR     = CKD-EPI equation from CR, Age and Sex
#       PAR      = PLT / ALB
#       NPR      = NE_C / PLT
#       INR      = (PT / 13.1)^1.31
#       TyG      = log(1594.26 * TG * GLU / 2)
#    They are recalculated AFTER every completed MICE dataset is created.
# 5) Perform TRUE multiple imputation inside each CV split:
#       - each fold produces MICE_M completed BASIC-variable datasets;
#       - analysis rows fit each imputation model;
#       - assessment rows are ignore = TRUE and never estimate imputation rules;
#       - derived predictors are calculated separately within every completed dataset;
#       - each completed dataset is modeled separately;
#       - OOF probabilities are pooled across imputations by arithmetic mean.
# 6) Standardization + SMOTE + Tomek are performed inside the tidymodels recipe.
# 7) Tune SVM and XGBoost across all fold-imputation resamples using Bayesian optimization.
# 8) Generate pooled aligned OOF predictions and fit an Elastic Net meta-learner.
# 9) Fit Platt calibration on meta-learner OOF probabilities and determine a Youden threshold.
# 10) On the full development cohort, create MICE_M completed BASIC-variable datasets,
#     derive the six deterministic predictors, and refit one SVM and one XGBoost
#     model per imputation.
#
# IMPORTANT
# - The final 16 predictors and the SVM + XGBoost architecture are NOT re-selected here.
# - Derived predictors are NEVER passed to mice().
# - Outcome PDstage is NEVER used for imputation.
# - External validation data must NOT be used anywhere in this training script.
# - MICE_M = 5 is a practical first true-MI run; 10 or 20 can be used for sensitivity
#   analysis, but computational cost rises approximately linearly with MICE_M.
# ==============================================================================

