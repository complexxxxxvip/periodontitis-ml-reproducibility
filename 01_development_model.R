    predictor = meta_oof$Stack_calibrated,
    levels = c("Stage0", "Stage1"),
    direction = "<",
    quiet = TRUE
  )

  threshold_info <- pROC::coords(
    roc_for_threshold,
    x = "best",
    best.method = "youden",
    ret = c("threshold", "sensitivity", "specificity"),
    transpose = FALSE
